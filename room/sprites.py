"""Pixel-art sprites, drawn as grids of letters.

Each sprite is a list of equal-length strings. Every letter is one pixel and
stands for a color in PALETTE ("." = transparent). The actual colors live in
static/css/theme.css as --px-<name> variables, so the whole palette can be
changed there without touching the art.

render(name) turns a sprite into an inline <svg> that the templates insert
into the page. Larger repeating things (rugs, the floor, the wallpaper) are
generated by small functions further down instead of drawn by hand.
"""
