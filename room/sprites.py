def size(name):
    """(width, height) of a sprite in art pixels."""
    rows = SPRITES[name]
    return len(rows[0]), len(rows)


def _rects(rows):
    """SVG rectangles for a sprite, merging same-colored runs in each row."""
    parts = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            end = x + 1
            while end < len(row) and row[end] == ch:
                end += 1
            if ch != ".":
                parts.append(
                    f'<rect class="px-{PALETTE[ch]}" x="{x}" y="{y}" '
                    f'width="{end - x}" height="1"/>'
                )
            x = end
    return "".join(parts)


@lru_cache(maxsize=None)
def render(name, extra_class=""):
    """Inline <svg> for a sprite, scaled up by SCALE."""
    w, h = size(name)
    classes = f"sprite sprite-{name} {extra_class}".strip()
    return Markup(
        f'<svg class="{classes}" viewBox="0 0 {w} {h}" width="{w * SCALE}" '
        f'height="{h * SCALE}" shape-rendering="crispEdges" aria-hidden="true">'
        f"{_rects(SPRITES[name])}</svg>"
    )


@lru_cache(maxsize=None)
def render_pattern(tile, width, height, extra_class=""):
    """Inline <svg> of size width x height (art pixels) filled with a tile."""
    tw, th = size(tile)
    pid = f"pattern-{tile}"
    return Markup(
        f'<svg class="{extra_class}" viewBox="0 0 {width} {height}" '
        f'width="{width * SCALE}" height="{height * SCALE}" '
        f'shape-rendering="crispEdges" aria-hidden="true">'
        f'<defs><pattern id="{pid}" width="{tw}" height="{th}" '
        f'patternUnits="userSpaceOnUse">{_rects(SPRITES[tile])}</pattern></defs>'
        f'<rect width="{width}" height="{height}" fill="url(#{pid})"/></svg>'
    )
