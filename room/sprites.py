def _rug(width, height, border, base, petal, center):
    """A rectangular rug with a double border and little flowers."""
    flower = {(1, 0): petal, (0, 1): petal, (2, 1): petal, (1, 2): petal, (1, 1): center}
    rows = []
    for y in range(height):
        row = ""
        for x in range(width):
            edge = min(x, y, width - 1 - x, height - 1 - y)
            if edge in (0, 2):
                row += border
            elif edge == 1:
                row += "c"
            elif edge >= 4:
                row += flower.get(((x - 4) % 8, (y - 4) % 7), base)
            else:
                row += base
        rows.append(row)
    return rows


def _round_rug(width, height):
    """An oval pink rug with a darker rim and light middle."""
    cx, cy = width / 2, height / 2
    rows = []
    for y in range(height):
        row = ""
        for x in range(width):
            d = ((x + 0.5 - cx) / cx) ** 2 + ((y + 0.5 - cy) / cy) ** 2
            row += "." if d > 1 else "P" if d > 0.75 else "p" if d > 0.4 else "l"
        rows.append(row)
    return rows


def _doily(size):
    """A round lace doily with a ring of holes."""
    r = size / 2
    rows = []
    for y in range(size):
        row = ""
        for x in range(size):
            dx, dy = x + 0.5 - r, y + 0.5 - r
            d = math.hypot(dx, dy) / r
            slice_ = int((math.atan2(dy, dx) + math.pi) / (2 * math.pi) * 16)
            if d > 1:
                row += "."
            elif d > 0.88:
                row += "C"
            elif d > 0.7:
                row += "." if slice_ % 2 == 0 else "c"
            elif d > 0.6:
                row += "C"
            elif d > 0.25:
                row += "C" if (x + y) % 4 == 0 else "c"
            else:
                row += "C"
        rows.append(row)
    return rows


def _herringbone_tile(unit=4):
    """One repeating 16x16 tile of herringbone wood floor.

    Planks are 2 units long and 1 unit wide. Within the 4x4-unit tile,
    (column - row) % 4 tells which plank part a unit belongs to:
    0/1 = left/right half of a flat plank, 3/2 = top/bottom half of a
    standing plank.
    """
    rows = []
    for py in range(4 * unit):
        row = ""
        for px in range(4 * unit):
            ux, uy, sx, sy = px // unit, py // unit, px % unit, py % unit
            part = (ux - uy) % 4
            last = unit - 1
            if part in (0, 1):  # flat plank
                line = sy == last or (part == 1 and sx == last)
                row += "3" if line else "1"
            else:               # standing plank
                line = sx == last or (part == 2 and sy == last)
                row += "3" if line else "2"
        rows.append(row)
    return rows


def _tictactoe_table():
    """A low table with a tic-tac-toe grid painted on top."""
    marks = {(0, 0): "r", (1, 1): "M", (2, 0): "M", (0, 2): "r", (2, 2): "r"}
    grid = []
    for gy in range(11):
        row = ""
        for gx in range(11):
            if gx in (3, 7) or gy in (3, 7):
                row += "P"  # grid lines
            elif gx % 4 == 1 and gy % 4 == 1:
                row += marks.get((gx // 4, gy // 4), "c")  # X (rose) / O (mint)
            else:
                row += "c"
        grid.append(row)
    return (
        ["o" * 15, "o" + "c" * 13 + "o"]
        + ["oc" + row + "co" for row in grid]
        + ["o" + "c" * 13 + "o", "o" + "C" * 13 + "o", "o" * 15, ".oo.........oo."]
    )


