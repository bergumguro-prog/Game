# shape letter -> palette letter, per side
COLORS = {
    "w": {"#": "w", "+": "C", "*": "o"},
    "b": {"#": "B", "+": "H", "*": "n"},
}


def colored(shape, side):
    """Fill a shape with a side's colors and outline it."""
    colors = COLORS[side]
    h, w = len(shape), len(shape[0])

    def filled(x, y):
        return 0 <= x < w and 0 <= y < h and shape[y][x] != "."

    rows = []
    for y in range(h):
        row = ""
        for x in range(w):
            ch = shape[y][x]
            if ch != ".":
                row += colors[ch]
            elif any(filled(x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1)):
                row += "o"
            else:
                row += "."
        rows.append(row)
    return rows


for _side in COLORS:
    for _kind, _shape in SHAPES.items():
        sprites.SPRITES[f"chess-{_side}{_kind}"] = colored(_shape, _side)


def sprite_name(piece):
    """chess.Piece -> sprite name, e.g. white knight -> "chess-wn"."""
    side = "w" if piece.color else "b"
    return f"chess-{side}{piece.symbol().lower()}"
